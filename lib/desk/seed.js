/** Backfill older state: missing collections become empty arrays, missing version becomes 1. */
export function migrateState(state) {
  if (!state || typeof state !== 'object') return buildSeed()
  const next = { ...state }
  next.version = Number(next.version) || 1
  for (const key of ['todos', 'projects', 'papers', 'ideas', 'notes', 'chat', 'metrics', 'tagRegistry']) {
    if (!Array.isArray(next[key])) next[key] = []
  }
  if (!next.settings || typeof next.settings !== 'object') next.settings = { assistant: null, language: 'en', dockOpen: true }
  return next
}
