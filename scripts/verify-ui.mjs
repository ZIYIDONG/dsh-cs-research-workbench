import fs from 'node:fs/promises';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { definitions } from '../lib/index.js';
import { registerUiCommand } from '../lib/ui-command.js';
const pluginDir=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
await fs.mkdir(path.join(pluginDir,'.test-artifacts'),{recursive:true});
const root=await fs.mkdtemp(path.join(pluginDir,'.test-artifacts','ui-'));
let command;const cleanups=[];
const ctx={get:key=>key==='commands'?{register(def){command=def;return()=>{command=undefined;};}}:undefined,effect:fn=>cleanups.push(fn())};
registerUiCommand(ctx,definitions(ctx));
assert.equal(command.name,'dsh-csrw');assert.equal(command.recordInput,false);
const signal=new AbortController().signal;
const invoke=(operation,args={},confirmed=false)=>command.handler({rawInput:JSON.stringify({operation,args:{workspace:root,...args},confirmed}),agent:{id:'fixture'},signal});
assert.equal((await invoke('dsh_csrw_config_set',{key:'obsidian.autoDetect',value:false})).kind,'error');
assert.equal((await invoke('dsh_csrw_config_set',{key:'obsidian.autoDetect',value:false},true)).kind,'success');
const config=await invoke('dsh_csrw_config_show');assert.equal(JSON.parse(config.text).config.obsidian.autoDetect,false);
assert.equal((await invoke('dsh_csrw_snapshot_restore',{},true)).kind,'error');
assert.equal((await invoke('dsh_csrw_config_set',{key:'nutstore.password',value:'do-not-store'},true)).kind,'error');
assert.equal((await invoke('dsh_csrw_health',{workspace:'relative'})).kind,'error');
assert.equal((await command.handler({rawInput:'not-json',agent:{id:'fixture'},signal})).kind,'error');
const aborted=new AbortController();aborted.abort(new Error('cancelled fixture'));assert.equal((await command.handler({rawInput:JSON.stringify({operation:'dsh_csrw_health',args:{workspace:root}}),agent:{id:'fixture'},signal:aborted.signal})).kind,'error');
const cli=line=>command.handler({rawInput:line,agent:{id:'fixture'},signal});
const help=await cli('help');assert.equal(help.kind,'success');assert.ok(help.text.includes('config show'),'help lists operations');
const shown=await cli('config show --workspace "'+root+'"');assert.equal(shown.kind,'success');assert.equal(JSON.parse(shown.text).config.obsidian.autoDetect,false);
assert.equal((await cli('config set --workspace "'+root+'" --key obsidian.autoDetect --value true')).kind,'error','cli write needs --confirm');
assert.equal((await cli('config set --workspace "'+root+'" --key obsidian.autoDetect --value true --confirm')).kind,'success');
assert.equal(JSON.parse((await cli('config show --workspace "'+root+'"')).text).config.obsidian.autoDetect,true);
assert.equal((await cli('snapshot restore --workspace "'+root+'" --confirm')).kind,'error','restore stays unexposed');
assert.equal((await cli('config show')).kind,'error','cli needs an absolute workspace');
assert.equal((await cli('--bogus x')).kind,'error');
assert.equal((await cli('')).kind,'error');
cleanups.forEach(fn=>fn());assert.equal(command,undefined);
let client;const registered=[],disposers=[];
const sandbox={window:{__ModuleLoader__:{load(def){client=def;}}}};
vm.runInNewContext(await fs.readFile(path.join(pluginDir,'client.js'),'utf8'),sandbox);
assert.equal(client.id,'dsh-cs-research-workbench');
const api=client.factory(name=>{assert.equal(name,'react');return {createElement(){}};});
api.apply({effect:fn=>disposers.push(fn()),locale:{register:()=>()=>{},bind:()=>key=>key},slots:{inject:(name,fn)=>disposers.push(fn()),register:(options,component)=>{registered.push({options,component});return()=>registered.pop();}}});
assert.deepEqual(registered.map(e=>e.options.name),['main','sidebar.panellist','settings.section','settings.section.icon','plugins.bundle.config']);
assert.equal(registered[0].options.key,registered[1].options.id);
assert.equal(registered[2].options.id,'dsh-csrw-ui');
assert.ok(registered.every(e=>typeof e.component==='function'));
for(const dispose of disposers.reverse())dispose();assert.equal(registered.length,0);
console.log(JSON.stringify({uiCommand:'passed',cliMode:'passed',help:'passed',sharedConfiguration:'passed',writeConfirmation:'passed',sensitiveConfigRejection:'passed',cancel:'passed',slots:5,disposal:'passed'}));
